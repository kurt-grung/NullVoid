#!/usr/bin/env node
/**
 * Build the benign package list used for ML training (ml-model/benign-packages.txt).
 *
 * Samples the npm registry search API sorted by popularity across a spread of
 * generic queries, dedupes, drops anything that appears in an exclusion list
 * (e.g. GHSA malware names) and keeps the top-N by monthly downloads.
 *
 * Usage:
 *   node ml-model/fetch-top-packages.js --out ml-model/benign-packages.txt --min 1500
 *   node ml-model/fetch-top-packages.js --exclude-file ml-model/.cache/ghsa-malware.txt
 *
 * The output is one package name per line with a `# downloads/month` comment,
 * so the list is reviewable in a diff. "Popular" is not proof of "benign", but
 * a package in the top few thousand by downloads that has no malware advisory
 * is the best ground truth available at scale; anything that later receives a
 * malware advisory is removed on the next export.
 */

const fs = require('fs');
const path = require('path');

const REGISTRY_SEARCH = 'https://registry.npmjs.org/-/v1/search';
const PAGE = 250;

// Generic queries so results are not dominated by one ecosystem.
const QUERIES = [
  'util',
  'cli',
  'react',
  'node',
  'typescript',
  'test',
  'http',
  'parser',
  'babel',
  'webpack',
  'eslint',
  'stream',
  'promise',
  'json',
  'file',
  'string',
  'array',
  'date',
  'css',
  'vue',
  'express',
  'async',
  'crypto',
  'color',
  'path',
  'object',
  'regex',
  'buffer',
  'types',
  'plugin',
];

function parseArgs(argv) {
  const out = { out: 'ml-model/benign-packages.txt', min: 1500, exclude: [], pagesPerQuery: 4 };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--out' && argv[i + 1]) out.out = argv[++i];
    else if (a === '--min' && argv[i + 1]) out.min = parseInt(argv[++i], 10) || out.min;
    else if (a === '--pages' && argv[i + 1])
      out.pagesPerQuery = parseInt(argv[++i], 10) || out.pagesPerQuery;
    else if (a === '--exclude-file' && argv[i + 1]) {
      const p = argv[++i];
      if (fs.existsSync(p)) {
        for (const line of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
          const name = line.replace(/#.*$/, '').trim();
          if (name) out.exclude.push(name);
        }
      }
    }
  }
  return out;
}

async function searchPage(text, from) {
  const url = `${REGISTRY_SEARCH}?text=${encodeURIComponent(text)}&size=${PAGE}&from=${from}&popularity=1.0&quality=0.0&maintenance=0.0`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`registry search ${res.status} for ${text}`);
  const body = await res.json();
  return Array.isArray(body.objects) ? body.objects : [];
}

function isCandidate(obj) {
  const pkg = obj.package || {};
  if (!pkg.name) return false;
  // Types stubs and deprecated placeholders add nothing to a benign class.
  if (pkg.name.startsWith('@types/')) return false;
  if (/security holding package/i.test(pkg.description || '')) return false;
  return true;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const exclude = new Set(args.exclude);
  const seen = new Map(); // name -> monthly downloads

  for (const q of QUERIES) {
    for (let page = 0; page < args.pagesPerQuery; page++) {
      let objects;
      try {
        objects = await searchPage(q, page * PAGE);
      } catch (e) {
        console.warn(`  ! ${e.message}`);
        break;
      }
      if (objects.length === 0) break;
      for (const obj of objects) {
        if (!isCandidate(obj)) continue;
        const name = obj.package.name;
        if (exclude.has(name)) continue;
        const monthly = obj.downloads?.monthly ?? 0;
        if (!seen.has(name) || seen.get(name) < monthly) seen.set(name, monthly);
      }
    }
    process.stdout.write(`  ${q}: ${seen.size} unique so far\n`);
  }

  const ranked = [...seen.entries()].filter(([, dl]) => dl >= 100000).sort((a, b) => b[1] - a[1]);

  if (ranked.length < args.min) {
    console.error(
      `Only ${ranked.length} packages found; need at least ${args.min}. Increase --pages.`
    );
    process.exitCode = 1;
  }

  const lines = [
    '# Benign training set: popular npm packages with no GHSA malware advisory.',
    `# Generated by ml-model/fetch-top-packages.js on ${new Date().toISOString().slice(0, 10)}; ${ranked.length} packages.`,
    '# One name per line; the comment is monthly downloads at generation time.',
    '',
    ...ranked.map(([name, dl]) => `${name}  # ${dl}`),
    '',
  ];
  fs.mkdirSync(path.dirname(args.out), { recursive: true });
  fs.writeFileSync(args.out, lines.join('\n'));
  console.log(`Wrote ${ranked.length} packages to ${args.out}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
